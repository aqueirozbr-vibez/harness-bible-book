#!/usr/bin/env python3
"""Regenerate the status section of book/CHAPTER-MAP.md and book/FAILURE-INDEX.md from the book's files.
Run after any chapter step. The map's scope rows are canonical and are never edited here; only the status
section below the marker is rewritten."""
import glob,re,os,datetime,subprocess,sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
MARK="\n<!-- STATUS (generated; do not edit by hand) -->\n"
def words(t): return len(re.sub(r"```.*?```","",t,flags=re.S).split())
rows=[]
for ch in [f"{i:02d}" for i in range(0,41)]:
    f=glob.glob(f"book/part*/ch{ch}-*.md"); t=open(f[0]).read() if f else ""
    title=(re.search(r"^# Chapter \d\d — (.+)$",t,re.M) or re.search(r"^# (.+)$",t,re.M)); title=title.group(1) if title else ""
    drafted=words(t)>800; w=words(t) if drafted else 0
    labdir=glob.glob(f"labs/ch{ch}-*"); labst="—"
    if labdir and os.path.exists(f"{labdir[0]}/run.py"):
        r=subprocess.run([sys.executable,"run.py"],cwd=labdir[0],capture_output=True,text=True,timeout=900); open(f"{labdir[0]}/results/run.txt","w").write(r.stdout+r.stderr); labst="REPRODUCED" if r.returncode==0 else "FAIL"
    if ch=="00": labst="none (by row)"
    reg=os.path.exists(f"book/registry/ch{ch}.md"); ver=os.path.exists(f"book/registry/ch{ch}-verify.md"); red=os.path.exists(f"book/registry/ch{ch}-redteam.md"); integ=os.path.exists(f"book/registry/ch{ch}-integrate.md")
    links="—"
    if drafted and ch!="00":
        m=re.search(r"## \d\d?\.9 Sources\n(.*)",t,re.S); n=len(re.findall(r"^\| \d",m.group(1),re.M)) if m else 0; nf=m.group(1).count("needs fetch") if m else 0; links=f"{n} rows, {nf} needs fetch"
    rows.append((ch,title[:38],"y" if drafted else "—",w,labst,"y" if reg else "—","y" if ver else "—","y" if red else "—","y" if integ else "—",links))
done=sum(1 for r in rows if r[2]=="y"); labs_ok=sum(1 for r in rows if r[4]=="REPRODUCED")
status=[MARK,f"## Status — {datetime.date.today().isoformat()}","",f"{done}/41 drafted · {labs_ok} labs reproducing · {sum(1 for r in rows if r[6]=='y')} verified · {sum(1 for r in rows if r[7]=='y')} red-teamed · {sum(1 for r in rows if r[8]=='y')} integrated. Words are prose + tables (code excluded), the linter's count.","","| Ch | Title | Drafted | Words | Lab | Registry | Verify | Redteam | Integrate | Sources |","|---|---|---|---|---|---|---|---|---|---|"]
status += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3] or '—'} | {r[4]} | {r[5]} | {r[6]} | {r[7]} | {r[8]} | {r[9]} |" for r in rows]
status += ["","Book-level files: GLOSSARY.md, SOURCES.md (with links), TOOLKIT.md, CHANGELOG.md, FAILURE-INDEX.md, PILOT-REPORT.md. Regenerate with `python scripts/update_map.py`."]
m=open("book/CHAPTER-MAP.md").read(); base=m.split(MARK)[0].rstrip()+"\n"
open("book/CHAPTER-MAP.md","w").write(base+"\n".join(status)+"\n")
# failure index
idx=[]
for g in sorted(glob.glob("book/part*/ch*.md")):
    t=open(g).read(); ch=re.search(r"ch(\d\d)",g).group(1)
    if words(t)<800 or ch in ("00","33"): continue
    mm=re.search(r"## \d\d?\.5 Failure\n(.*?)\n## ",t,re.S)
    if not mm: continue
    for line in mm.group(1).splitlines():
        if line.startswith("| ") and not line.startswith("| Failure mode") and not line.startswith("|---"):
            cells=[x.strip() for x in line.strip("|").split("|")]
            if len(cells)==5: idx.append((ch,*cells))
out=[f"# Failure index — every failure mode in the book (generated {datetime.date.today().isoformat()})","",f"{len(idx)} rows from the Failure layer of every drafted chapter, regenerated by scripts/update_map.py. Chapter 33 carries the fifteen recurring modes with full entries; this index is the complete cross-index the map calls for.","","| Ch | Failure mode | Mechanism | Detection signal | Mitigation | Owner |","|---|---|---|---|---|---|"]+[f"| {' | '.join(r)} |" for r in idx]
open("book/FAILURE-INDEX.md","w").write("\n".join(out))
print(f"map status: {done}/41 drafted, {labs_ok} labs; failure index {len(idx)} rows")
